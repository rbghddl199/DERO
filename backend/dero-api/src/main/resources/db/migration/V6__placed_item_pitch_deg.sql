-- V6 — placed_item.pitch_deg 신설.
-- docs/context/erd.md(스키마 정본)에서 파생한다 — 이 컬럼은 2026-08-04에 승인됐고
-- (개정표 "`placed_item.pitch_deg` 신설 (2026-08-04, 승인 박동규, ADR-0023, DERO-407)")
-- 정본 표에도 실려 있다. 문서가 앞서 간 상태를 DDL이 따라잡는 것이다.
-- erd.md는 손대지 않는다(동결 — docs/HARNESS-RULES.md §4).
--
-- 아이템 앞뒤 기울기(pitch)다. ADR-0023이 자세 결정 권한을 접촉 솔버에서 사용자로 넘겼고
-- (결정 2) 사용자가 준 자세는 로드 시 재계산하지 않으므로 저장할 자리가 있어야 한다 — 없으면
-- 리로드마다 기울기가 소실돼 개정 자체가 성립하지 않는다.
--
-- 타입 근거는 rotation_deg와 같다(erd.md 전역 규칙 "각도 예외") — 사용자가 연속으로 조작하는
-- 인스턴스 각도라 정수로 자르면 경계선상 배치가 저장 전 "적합"이었다가 재로드 후 "위반"으로
-- 뒤집힌다(경계·스태킹 판정이 회전 footprint 기준).
--
-- 허용 범위 −75.00~75.00의 상한은 클라이언트가 강제하고 CHECK를 걸지 않는다 — 서버는 값을
-- 저장만 한다(ADR-0023 결정 3, emitter_brightness_scale과 같은 방침).
--
-- NOT NULL + DEFAULT 0이라 기존 행은 즉시 백필된다 — PG 11+는 기본값을 카탈로그에만 적고
-- 테이블을 재작성하지 않으므로 잠금 시간이 행 수에 비례하지 않는다. 기존 거치 배치는 리로드 시
-- 평평해지고 사용자가 고친다(ADR-0023 파급 — 솔버 출시가 2026-08-03이라 데이터 실질 0).
ALTER TABLE placed_item ADD COLUMN pitch_deg NUMERIC(6, 2) NOT NULL DEFAULT 0;

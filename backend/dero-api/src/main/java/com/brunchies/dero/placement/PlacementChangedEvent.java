/**
 * 배치가 바뀌었다 — 저장·삭제·공개 전환이 커밋된 뒤 검색 색인을 맞추라는 신호(ADR-0019 결정 3 ·
 * ADR-0027).
 *
 * <p><b>무엇이 바뀌었는지는 싣지 않는다</b>({@code PostChangedEvent}와 같은 이유) — 받는 쪽이
 * 커밋된 상태를 다시 읽어 "있으면 색인, 없으면 제거"로 판정한다. 이벤트에 종류를 실으면 발행부와
 * 색인부가 각자 상태를 추측하게 되고, 둘이 갈리는 순간 색인이 조용히 어긋난다.
 *
 * <p><b>{@link PublishStatus} 전이는 발행 사유가 아니다</b> — 전량 색인이라 {@code PRIVATE}도
 * 문서가 있고 노출 판정은 Postgres가 한다(ADR-0027 결정 4). 공개 전환에서 발행하는 이유는 상태가
 * 아니라 <b>그 자리에서 태그가 들어오기 때문</b>이다(결정 5).
 *
 * <p>아이템·책상 배치만 바뀐 저장도 발행한다 — 저장 경로가 하나라 거기서 갈라 봐야 "제목이 안
 * 바뀐 저장"을 추측하는 코드만 늘고, 재색인 1건은 싸다. 좋아요·북마크·썸네일은 발행하지 않는다:
 * 색인에 실리는 값이 제목·설명·태그·작성자 id뿐이라 문서가 그대로다.
 */
